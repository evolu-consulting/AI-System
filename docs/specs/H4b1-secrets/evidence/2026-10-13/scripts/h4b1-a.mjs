// UAT H4b-1 phần A: Studio -> Secrets (tạo mỗi kind, danh sách không lộ giá trị, rotate, xoá chưa dùng)
import { launch, studioLogin, mkSnap, mkStep, expect } from "./lib.mjs";
const OUT = process.argv[2];
const { browser, page } = await launch(OUT);
const snap = mkSnap(OUT);
const { step, save } = mkStep(OUT, () => ({ A: page }), snap);
const table = () => page.getByRole("table", { name: "Danh sách secret" });
const row = (n) => table().getByRole("row").filter({ hasText: n });
const tab = (t) => page.getByRole("tablist", { name: "Loại secret" }).getByRole("tab", { name: t });
const toast = () => page.getByRole("region", { name: "Notifications" });
const V_PROV = "sk-ant-uat-Zx9Pq7Lm-provider";
const V_KH = "mock-kh-key", V_KH_WRONG = "uat-wrong-key-Zx9Pq7Lm";
const V_ROT = "sk-ant-uat-ROTATED-Qw3Er5Ty";
const seen = [];
page.on("response", async (r) => { if (r.url().includes("/studio/api/secrets")) { try { seen.push(await r.text()); } catch {} } });
const bodyText = () => page.locator("html").innerHTML();
async function create({ name, value }) {
  await page.getByRole("button", { name: "+ Thêm secret" }).first().click();
  const dlg = page.getByRole("dialog", { name: "Thêm secret" });
  await dlg.getByRole("textbox", { name: "Tên" }).fill(name);
  await dlg.getByLabel("Giá trị", { exact: true }).fill(value);
  await dlg.getByRole("button", { name: "Lưu" }).click();
  await expect(dlg.getByRole("status").filter({ hasText: "Đã lưu · v1" })).toBeVisible();
  return dlg;
}
await step("01", "Đăng nhập Studio (platform admin) → menu Secrets", async () => {
  await studioLogin(page);
  await page.getByRole("navigation", { name: "Menu Studio" }).getByRole("link", { name: "Secrets" }).click();
  await expect(page.getByRole("heading", { name: "Secrets", exact: true })).toBeVisible();
  for (const t of ["Provider API key", "Khoá nguồn (git)", "Khoá KnowledgeHub"]) await expect(tab(t)).toBeVisible();
  await snap(page, "01-A-secrets-empty");
});
await step("02", "Tạo provider_api_key anthropic-main: password, nút Hiện, Sheet ở lại Đã lưu v1, ô rỗng", async () => {
  await page.getByRole("button", { name: "+ Thêm secret" }).first().click();
  const dlg = page.getByRole("dialog", { name: "Thêm secret" });
  await dlg.getByRole("textbox", { name: "Tên" }).fill("anthropic-main");
  const f = dlg.getByLabel("Giá trị", { exact: true });
  await expect(f).toHaveAttribute("type", "password");
  await f.fill(V_PROV);
  await expect(dlg.getByRole("button", { name: "Hiện giá trị đang gõ" })).toBeVisible();
  await snap(page, "02-A-provider-sheet-filled");
  await dlg.getByRole("button", { name: "Lưu" }).click();
  await expect(dlg.getByRole("status").filter({ hasText: "Đã lưu · v1" })).toBeVisible();
  await expect(f).toHaveValue("");
  await snap(page, "03-A-provider-sheet-saved");
  await dlg.getByRole("button", { name: "Đóng" }).click();
  await expect(dlg).toBeHidden();
  await expect(toast()).toContainText("Đã thêm anthropic-main");
  await expect(row("anthropic-main")).toContainText("Đã lưu");
  await snap(page, "04-A-provider-list");
});
await step("03", "Tab Khoá KnowledgeHub: tạo kh-main (nền tảng, = khoá mock) và kh-wrong", async () => {
  await tab("Khoá KnowledgeHub").click();
  await expect(page.getByText("Chưa có khoá KnowledgeHub.")).toBeVisible();
  await snap(page, "05-A-kh-empty");
  let dlg = page.getByRole("dialog", { name: "Thêm secret" });
  await page.getByRole("button", { name: "+ Thêm secret" }).first().click();
  await expect(dlg.getByRole("combobox", { name: "Phạm vi" })).toBeVisible();
  await snap(page, "06-A-kh-sheet-scope");
  await dlg.getByRole("button", { name: "Huỷ" }).click();
  await expect(dlg).toBeHidden();
  dlg = await create({ name: "kh-main", value: V_KH });
  await expect(dlg.getByRole("combobox", { name: "Phạm vi" })).toBeDisabled();
  await dlg.getByRole("button", { name: "Đóng" }).click();
  await expect(dlg).toBeHidden();
  dlg = await create({ name: "kh-wrong", value: V_KH_WRONG });
  await dlg.getByRole("button", { name: "Đóng" }).click();
  await expect(row("kh-main")).toBeVisible();
  await expect(row("kh-wrong")).toBeVisible();
  await expect(table().getByRole("columnheader", { name: "Tenant" })).toBeVisible();
  await snap(page, "07-A-kh-list");
});
await step("04", "Tab Khoá nguồn (git): chỉ đọc, không có nút thêm (tạo ở Admin > Nguồn)", async () => {
  await tab("Khoá nguồn (git)").click();
  await expect(page.getByRole("button", { name: "+ Thêm secret" })).toHaveCount(0);
  await expect(page.getByText("Khoá nguồn do tenant admin tạo ở màn Nguồn.", { exact: false }).first()).toBeVisible();
  await snap(page, "08-A-source-tab");
});
await step("05", "Danh sách không lộ giá trị: DOM + mọi response /secrets không chứa chuỗi khoá; không có nút Xem", async () => {
  await tab("Provider API key").click();
  await expect(row("anthropic-main")).toBeVisible();
  const html = await bodyText();
  for (const v of [V_PROV, V_KH_WRONG]) expect(html).not.toContain(v);
  const all = seen.join("\n");
  for (const v of [V_PROV, V_KH_WRONG, V_KH]) expect(all).not.toContain(v);
  await expect(table().getByRole("button", { name: /Xem|Hiện/ })).toHaveCount(0);
  await snap(page, "09-A-list-no-values");
});
await step("06", "Xoay khoá anthropic-main: Sheet Thay giá trị, ô rỗng, tên không sửa, Lưu → v2", async () => {
  await row("anthropic-main").getByRole("button", { name: "Thay giá trị" }).click();
  const dlg = page.getByRole("dialog", { name: "Thay giá trị · anthropic-main" });
  await expect(dlg.getByRole("textbox", { name: "Tên" })).toHaveCount(0);
  const f = dlg.getByLabel("Giá trị", { exact: true });
  await expect(f).toHaveValue("");
  await f.fill(V_ROT);
  await snap(page, "10-A-rotate-sheet");
  await dlg.getByRole("button", { name: "Lưu" }).click();
  await expect(dlg.getByRole("status").filter({ hasText: "Đã lưu · v2" })).toBeVisible();
  await snap(page, "11-A-rotate-saved");
  await dlg.getByRole("button", { name: "Đóng" }).click();
  await expect(toast()).toContainText("anthropic-main");
  expect(await bodyText()).not.toContain(V_ROT);
  expect(seen.join("\n")).not.toContain(V_ROT);
});
await step("07", "Validate: trường rỗng báo lỗi; trùng tên không tạo được", async () => {
  await page.getByRole("button", { name: "+ Thêm secret" }).first().click();
  const dlg = page.getByRole("dialog", { name: "Thêm secret" });
  await dlg.getByRole("button", { name: "Lưu" }).click();
  await snap(page, "12-A-validate-empty");
  await dlg.getByRole("textbox", { name: "Tên" }).fill("anthropic-main");
  await dlg.getByLabel("Giá trị", { exact: true }).fill("sk-dup-12345678");
  await dlg.getByRole("button", { name: "Lưu" }).click();
  await page.waitForTimeout(800);
  await snap(page, "13-A-validate-duplicate");
  await expect(dlg.getByRole("status").filter({ hasText: "Đã lưu" })).toHaveCount(0);
  await dlg.getByRole("button", { name: "Huỷ" }).click();
});
await step("08", "Xoá secret chưa dùng (kh-wrong): ConfirmDialog → Xoá → biến mất", async () => {
  await tab("Khoá KnowledgeHub").click();
  await row("kh-wrong").getByRole("button", { name: "Xoá" }).click();
  const dlg = page.getByRole("alertdialog", { name: "Xoá kh-wrong?" });
  await expect(dlg).toBeVisible();
  await snap(page, "14-A-delete-confirm");
  await dlg.getByRole("button", { name: "Xoá" }).click();
  await expect(row("kh-wrong")).toHaveCount(0);
  await snap(page, "15-A-delete-done");
  const d2 = await create({ name: "kh-wrong", value: V_KH_WRONG });
  await d2.getByRole("button", { name: "Đóng" }).click();
});
save(); await browser.close();
