// Soi giao diện tiếng Anh (EN): admin canvas (julian.bui) + chat run page (thomas.tran). Chỉ chụp ảnh + ghi chữ để soi tràn/thiếu dịch.
import { chromium, EVD } from "./pw.mjs";
import { writeFileSync } from "node:fs";
import { q } from "./lib2.mjs";
const RUN = q("select id from hub.process_runs where process_def_id=(select id from hub.process_defs where key='pb2-uat-edit' and tenant_id='01a11c1d-ca4e-7000-b4eb-212defbb548f') order by started_at desc limit 1");
const b = await chromium.launch();
const ctxEn = () => b.newContext({ locale: "en-US", viewport: { width: 1440, height: 1000 }, storageState: { cookies: [], origins: ["http://localhost:3000", "http://localhost:3100"].map((o) => ({ origin: o, localStorage: [{ name: "ai.locale", value: "en" }] })) } });
let c = await ctxEn();
let p = await c.newPage();
await p.goto("http://localhost:3000/login");
await p.getByRole("textbox", { name: "Company code" }).fill("evolu");
await p.getByRole("textbox", { name: "Username" }).fill("julian.bui");
await p.getByLabel("Password", { exact: true }).fill("1234567890");
await p.getByRole("button", { name: "Sign in", exact: true }).click();
await p.waitForURL((u) => !u.pathname.startsWith("/login"));
await p.goto("http://localhost:3000/processes");
await p.getByRole("table").getByRole("row").filter({ hasText: "pb2-uat-edit" }).getByRole("link").first().click();
await p.getByRole("application").waitFor({ timeout: 15000 });
const out = [];
const nodeBtn = p.getByRole("application").getByRole("button").filter({ hasText: /Tổng hợp|Summary/ }).first();
await nodeBtn.click();
await p.getByRole("tablist", { name: "View mode" }).evaluate((e) => e.scrollIntoView({ block: "start" }));
await p.evaluate(() => { for (const el of document.querySelectorAll("*")) if (el.scrollTop > 0 && el.scrollHeight > el.clientHeight + 50) el.scrollTop -= 90; });
await p.waitForTimeout(600);
await p.screenshot({ path: `${EVD}/12-EN-admin-canvas.png` });
out.push("ADMIN EN panel: " + (await p.getByRole("complementary", { name: "Stage details" }).innerText()).split("\n").filter((l) => l.length < 120).slice(-25).join(" / "));
await c.close();
c = await ctxEn();
p = await c.newPage();
await p.goto("http://localhost:3100/login");
await p.getByRole("textbox", { name: "Company code" }).fill("evolu");
await p.getByRole("textbox", { name: "Username" }).fill("thomas.tran");
await p.getByLabel("Password").fill("1234567890");
await p.getByRole("button", { name: "Sign in" }).click();
await p.waitForURL(/\/c\/new$/);
await p.goto(`http://localhost:3100/runs/${RUN}`);
await p.waitForTimeout(3500);
await p.screenshot({ path: `${EVD}/12-EN-chat-run.png` });
out.push("CHAT EN run: " + (await p.locator("main").innerText()).split("\n").slice(0, 40).join(" / "));
await c.close();
await b.close();
writeFileSync(EVD + "/en-text.txt", out.join("\n\n"));
console.log(out.join("\n\n").slice(0, 2500));
