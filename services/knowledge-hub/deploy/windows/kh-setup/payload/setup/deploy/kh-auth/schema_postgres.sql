-- Knowledge Hub (KH) access control tables, PostgreSQL. Same objects and rules as schema.sql (SAP HANA,
-- BTP prod); see that file for what every table, view and rule means. Used by the Windows install, where
-- Keycloak runs on a local PostgreSQL. The tables live in the Keycloak schema and belong to Keycloak.
--
-- Idempotent: tables are created only when missing, views and the trigger function are replaced.
-- Needs the Keycloak tables, so run it after Keycloak's first start. seed_postgres.py applies it.
-- Unquoted names fold to lower case, which is how Keycloak names its own tables on PostgreSQL.

CREATE TABLE IF NOT EXISTS KH_AUTH_ROLE (
    ROLE_CODE        VARCHAR(32)    NOT NULL PRIMARY KEY,
    DESCRIPTION      VARCHAR(500)   NOT NULL,
    PROJECT_SCOPE    VARCHAR(16)    NOT NULL DEFAULT 'all',
    CHECK (PROJECT_SCOPE IN ('all', 'tenant'))
);

CREATE TABLE IF NOT EXISTS KH_AUTH_PROJECT_LEVEL (
    LEVEL_CODE       VARCHAR(32)    NOT NULL PRIMARY KEY,
    LEVEL_RANK       INTEGER        NOT NULL,
    DESCRIPTION      VARCHAR(500)   NOT NULL
);

CREATE TABLE IF NOT EXISTS KH_AUTH_PERMISSION (
    PERMISSION_CODE  VARCHAR(64)    NOT NULL PRIMARY KEY,
    APPLIES_TO       VARCHAR(16)    NOT NULL,
    DESCRIPTION      VARCHAR(500)   NOT NULL,
    CHECK (APPLIES_TO IN ('project', 'kh'))
);

CREATE TABLE IF NOT EXISTS KH_AUTH_ROLE_PERMISSION (
    ROLE_CODE        VARCHAR(32)    NOT NULL REFERENCES KH_AUTH_ROLE (ROLE_CODE),
    PERMISSION_CODE  VARCHAR(64)    NOT NULL REFERENCES KH_AUTH_PERMISSION (PERMISSION_CODE),
    PRIMARY KEY (ROLE_CODE, PERMISSION_CODE)
);

CREATE TABLE IF NOT EXISTS KH_AUTH_LEVEL_PERMISSION (
    LEVEL_CODE       VARCHAR(32)    NOT NULL REFERENCES KH_AUTH_PROJECT_LEVEL (LEVEL_CODE),
    PERMISSION_CODE  VARCHAR(64)    NOT NULL REFERENCES KH_AUTH_PERMISSION (PERMISSION_CODE),
    PRIMARY KEY (LEVEL_CODE, PERMISSION_CODE)
);

CREATE TABLE IF NOT EXISTS KH_AUTH_PROJECT (
    PROJECT_ID       VARCHAR(128)   NOT NULL PRIMARY KEY,
    IS_SYSTEM        BOOLEAN        NOT NULL DEFAULT FALSE,
    STATE            VARCHAR(16)    NOT NULL DEFAULT 'active',
    CREATED_BY       VARCHAR(320),
    CREATED_AT       TIMESTAMP      NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    ORPHANED_AT      TIMESTAMP,
    DEFAULT_LEVEL    VARCHAR(32),
    VISIBILITY       VARCHAR(16)    NOT NULL DEFAULT 'private',
    CHECK (STATE IN ('active', 'orphan')),
    CHECK (VISIBILITY IN ('private', 'semi-public', 'public'))
);

CREATE TABLE IF NOT EXISTS KH_AUTH_VISIBILITY_ACCESS (
    VISIBILITY       VARCHAR(16)    NOT NULL,
    ROLE_CODE        VARCHAR(32)    NOT NULL REFERENCES KH_AUTH_ROLE (ROLE_CODE),
    LEVEL_CODE       VARCHAR(32)    NOT NULL REFERENCES KH_AUTH_PROJECT_LEVEL (LEVEL_CODE),
    PRIMARY KEY (VISIBILITY, ROLE_CODE)
);

CREATE TABLE IF NOT EXISTS KH_AUTH_GRANT (
    PROJECT_ID       VARCHAR(128)   NOT NULL REFERENCES KH_AUTH_PROJECT (PROJECT_ID) ON DELETE CASCADE,
    EMAIL            VARCHAR(320)   NOT NULL,
    LEVEL_CODE       VARCHAR(32)    NOT NULL REFERENCES KH_AUTH_PROJECT_LEVEL (LEVEL_CODE),
    GRANTED_BY       VARCHAR(320),
    GRANTED_AT       TIMESTAMP      NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    PRIMARY KEY (PROJECT_ID, EMAIL)
);

-- Views are dropped and recreated together: CREATE OR REPLACE cannot change a view's columns.
DROP VIEW IF EXISTS KH_AUTH_EFFECTIVE_KH_PERMISSION, KH_AUTH_EFFECTIVE_ACCESS, KH_AUTH_TENANT_PROJECT,
    KH_AUTH_USER_TENANT, KH_AUTH_USER_KH_ROLE, KH_AUTH_USER, KH_AUTH_USER_ROLE CASCADE;

CREATE VIEW KH_AUTH_USER_ROLE AS
    SELECT M.USER_ID, M.ROLE_ID FROM USER_ROLE_MAPPING M
    UNION
    SELECT UG.USER_ID, GR.ROLE_ID
      FROM USER_GROUP_MEMBERSHIP UG
      JOIN GROUP_ROLE_MAPPING GR ON GR.GROUP_ID = UG.GROUP_ID
    UNION
    SELECT UG.USER_ID, GR.ROLE_ID
      FROM USER_GROUP_MEMBERSHIP UG
      JOIN KEYCLOAK_GROUP G ON G.ID = UG.GROUP_ID
      JOIN GROUP_ROLE_MAPPING GR ON GR.GROUP_ID = G.PARENT_GROUP;

CREATE VIEW KH_AUTH_USER AS
    SELECT LOWER(U.EMAIL) AS EMAIL,
           U.ID AS USER_ID,
           U.FIRST_NAME,
           U.LAST_NAME,
           CASE WHEN SUM(CASE WHEN K.NAME = 'maintainer' THEN 1 ELSE 0 END) > 0 THEN 'maintainer' ELSE 'member' END AS ROLE_CODE,
           CASE WHEN U.ENABLED = TRUE THEN 'active' ELSE 'disabled' END AS STATUS
      FROM USER_ENTITY U
      JOIN REALM R ON R.ID = U.REALM_ID AND R.NAME = 'knowledge-hub'
      JOIN KH_AUTH_USER_ROLE M ON M.USER_ID = U.ID
      JOIN KEYCLOAK_ROLE K ON K.ID = M.ROLE_ID AND K.REALM_ID = R.ID AND K.CLIENT_ROLE = FALSE
                          AND K.NAME IN ('maintainer', 'member')
     WHERE U.EMAIL IS NOT NULL
     GROUP BY U.EMAIL, U.ID, U.FIRST_NAME, U.LAST_NAME, U.ENABLED;

CREATE VIEW KH_AUTH_USER_KH_ROLE AS
    SELECT DISTINCT LOWER(U.EMAIL) AS EMAIL, K.NAME AS ROLE_CODE
      FROM USER_ENTITY U
      JOIN REALM R ON R.ID = U.REALM_ID AND R.NAME = 'knowledge-hub'
      JOIN KH_AUTH_USER_ROLE M ON M.USER_ID = U.ID
      JOIN KEYCLOAK_ROLE K ON K.ID = M.ROLE_ID AND K.REALM_ID = R.ID AND K.CLIENT_ROLE = FALSE
      JOIN KH_AUTH_ROLE KR ON KR.ROLE_CODE = K.NAME
     WHERE U.EMAIL IS NOT NULL AND U.ENABLED = TRUE;

CREATE VIEW KH_AUTH_USER_TENANT AS
    SELECT LOWER(U.EMAIL) AS EMAIL, T.NAME AS TENANT, FALSE AS IS_ADMIN
      FROM USER_ENTITY U
      JOIN REALM R ON R.ID = U.REALM_ID AND R.NAME = 'knowledge-hub'
      JOIN USER_GROUP_MEMBERSHIP UG ON UG.USER_ID = U.ID
      JOIN KEYCLOAK_GROUP T ON T.ID = UG.GROUP_ID
      JOIN KEYCLOAK_GROUP ROOT ON ROOT.ID = T.PARENT_GROUP AND ROOT.NAME = 'tenants' AND ROOT.REALM_ID = R.ID
     WHERE U.EMAIL IS NOT NULL
    UNION
    SELECT LOWER(U.EMAIL) AS EMAIL, T.NAME AS TENANT, TRUE AS IS_ADMIN
      FROM USER_ENTITY U
      JOIN REALM R ON R.ID = U.REALM_ID AND R.NAME = 'knowledge-hub'
      JOIN USER_GROUP_MEMBERSHIP UG ON UG.USER_ID = U.ID
      JOIN KEYCLOAK_GROUP A ON A.ID = UG.GROUP_ID AND A.NAME = 'tenant-admins'
      JOIN KEYCLOAK_GROUP T ON T.ID = A.PARENT_GROUP
      JOIN KEYCLOAK_GROUP ROOT ON ROOT.ID = T.PARENT_GROUP AND ROOT.NAME = 'tenants' AND ROOT.REALM_ID = R.ID
     WHERE U.EMAIL IS NOT NULL
    UNION
    SELECT LOWER(U.EMAIL) AS EMAIL, T.NAME AS TENANT, FALSE AS IS_ADMIN
      FROM USER_ENTITY U
      JOIN REALM R ON R.ID = U.REALM_ID AND R.NAME = 'knowledge-hub'
      JOIN USER_GROUP_MEMBERSHIP UG ON UG.USER_ID = U.ID
      JOIN KEYCLOAK_GROUP A ON A.ID = UG.GROUP_ID AND A.NAME = 'tenant-admins'
      JOIN KEYCLOAK_GROUP T ON T.ID = A.PARENT_GROUP
      JOIN KEYCLOAK_GROUP ROOT ON ROOT.ID = T.PARENT_GROUP AND ROOT.NAME = 'tenants' AND ROOT.REALM_ID = R.ID
     WHERE U.EMAIL IS NOT NULL;

CREATE VIEW KH_AUTH_TENANT_PROJECT AS
    SELECT DISTINCT T.TENANT, P.PROJECT_ID
      FROM KH_AUTH_PROJECT P
      JOIN KH_AUTH_USER_TENANT T ON T.EMAIL = P.CREATED_BY
     WHERE P.IS_SYSTEM = FALSE;

-- D10: the project turns orphan when its owner count drops to zero (last owner removed or downgraded).
CREATE OR REPLACE FUNCTION KH_AUTH_GRANT_ORPHAN() RETURNS TRIGGER AS $$
BEGIN
    UPDATE KH_AUTH_PROJECT
       SET STATE = 'orphan', ORPHANED_AT = (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
     WHERE PROJECT_ID = OLD.PROJECT_ID
       AND STATE = 'active'
       AND IS_SYSTEM = FALSE
       AND NOT EXISTS (SELECT 1 FROM KH_AUTH_GRANT G
                        WHERE G.PROJECT_ID = OLD.PROJECT_ID AND G.LEVEL_CODE = 'owner');
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS KH_AUTH_GRANT_ORPHAN_ON_DELETE ON KH_AUTH_GRANT;
CREATE TRIGGER KH_AUTH_GRANT_ORPHAN_ON_DELETE AFTER DELETE ON KH_AUTH_GRANT
    FOR EACH ROW EXECUTE FUNCTION KH_AUTH_GRANT_ORPHAN();

DROP TRIGGER IF EXISTS KH_AUTH_GRANT_ORPHAN_ON_UPDATE ON KH_AUTH_GRANT;
CREATE TRIGGER KH_AUTH_GRANT_ORPHAN_ON_UPDATE AFTER UPDATE ON KH_AUTH_GRANT
    FOR EACH ROW EXECUTE FUNCTION KH_AUTH_GRANT_ORPHAN();

-- May EMAIL do PERMISSION_CODE on PROJECT_ID? Rules 1-6 as in schema.sql.
CREATE VIEW KH_AUTH_EFFECTIVE_ACCESS AS
    SELECT U.EMAIL, P.PROJECT_ID, RP.PERMISSION_CODE, 'role:' || KR.ROLE_CODE AS SOURCE
      FROM KH_AUTH_USER U
      JOIN KH_AUTH_USER_KH_ROLE KR ON KR.EMAIL = U.EMAIL
      JOIN KH_AUTH_ROLE R ON R.ROLE_CODE = KR.ROLE_CODE AND R.PROJECT_SCOPE = 'all'
      JOIN KH_AUTH_ROLE_PERMISSION RP ON RP.ROLE_CODE = KR.ROLE_CODE
      JOIN KH_AUTH_PERMISSION PM ON PM.PERMISSION_CODE = RP.PERMISSION_CODE AND PM.APPLIES_TO = 'project'
     CROSS JOIN KH_AUTH_PROJECT P
     WHERE U.STATUS = 'active'
    UNION ALL
    SELECT U.EMAIL, G.PROJECT_ID, LP.PERMISSION_CODE, 'level:' || G.LEVEL_CODE AS SOURCE
      FROM KH_AUTH_USER U
      JOIN KH_AUTH_GRANT G ON G.EMAIL = U.EMAIL
      JOIN KH_AUTH_PROJECT P ON P.PROJECT_ID = G.PROJECT_ID AND P.IS_SYSTEM = FALSE AND P.STATE = 'active'
      JOIN KH_AUTH_LEVEL_PERMISSION LP ON LP.LEVEL_CODE = G.LEVEL_CODE
     WHERE U.STATUS = 'active'
    UNION ALL
    SELECT U.EMAIL, P.PROJECT_ID, 'project.read' AS PERMISSION_CODE, 'system:read' AS SOURCE
      FROM KH_AUTH_USER U
     CROSS JOIN KH_AUTH_PROJECT P
     WHERE U.STATUS = 'active' AND P.IS_SYSTEM = TRUE
    UNION ALL
    SELECT U.EMAIL, TP.PROJECT_ID, RP.PERMISSION_CODE, 'tenant:' || A.TENANT AS SOURCE
      FROM KH_AUTH_USER U
      JOIN KH_AUTH_USER_KH_ROLE KR ON KR.EMAIL = U.EMAIL
      JOIN KH_AUTH_ROLE R ON R.ROLE_CODE = KR.ROLE_CODE AND R.PROJECT_SCOPE = 'tenant'
      JOIN KH_AUTH_ROLE_PERMISSION RP ON RP.ROLE_CODE = KR.ROLE_CODE
      JOIN KH_AUTH_PERMISSION PM ON PM.PERMISSION_CODE = RP.PERMISSION_CODE AND PM.APPLIES_TO = 'project'
      JOIN KH_AUTH_USER_TENANT A ON A.EMAIL = U.EMAIL AND A.IS_ADMIN = TRUE
      JOIN KH_AUTH_TENANT_PROJECT TP ON TP.TENANT = A.TENANT
     WHERE U.STATUS = 'active'
    UNION ALL
    SELECT U.EMAIL, P.PROJECT_ID, LP.PERMISSION_CODE, 'default:' || P.DEFAULT_LEVEL AS SOURCE
      FROM KH_AUTH_USER U
     CROSS JOIN KH_AUTH_PROJECT P
      JOIN KH_AUTH_LEVEL_PERMISSION LP ON LP.LEVEL_CODE = P.DEFAULT_LEVEL
     WHERE U.STATUS = 'active' AND P.DEFAULT_LEVEL IS NOT NULL AND P.IS_SYSTEM = FALSE AND P.STATE = 'active'
    UNION ALL
    SELECT U.EMAIL, P.PROJECT_ID, LP.PERMISSION_CODE, 'visibility:' || VA.ROLE_CODE AS SOURCE
      FROM KH_AUTH_USER U
      JOIN KH_AUTH_USER_KH_ROLE KR ON KR.EMAIL = U.EMAIL
      JOIN KH_AUTH_VISIBILITY_ACCESS VA ON VA.ROLE_CODE = KR.ROLE_CODE
      JOIN KH_AUTH_PROJECT P ON P.VISIBILITY = VA.VISIBILITY AND P.IS_SYSTEM = FALSE AND P.STATE = 'active'
      JOIN KH_AUTH_LEVEL_PERMISSION LP ON LP.LEVEL_CODE = VA.LEVEL_CODE
     WHERE U.STATUS = 'active';

CREATE VIEW KH_AUTH_EFFECTIVE_KH_PERMISSION AS
    SELECT DISTINCT U.EMAIL, RP.PERMISSION_CODE, 'role:' || KR.ROLE_CODE AS SOURCE
      FROM KH_AUTH_USER U
      JOIN KH_AUTH_USER_KH_ROLE KR ON KR.EMAIL = U.EMAIL
      JOIN KH_AUTH_ROLE_PERMISSION RP ON RP.ROLE_CODE = KR.ROLE_CODE
      JOIN KH_AUTH_PERMISSION PM ON PM.PERMISSION_CODE = RP.PERMISSION_CODE AND PM.APPLIES_TO = 'kh'
     WHERE U.STATUS = 'active';
