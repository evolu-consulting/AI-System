"""SQLite (or HANA, see app/sqldb.py) store for Claude Code hook rules, keyed by hook type.

Additive KH subsystem: a tiny local SQLite DB holding the FULL rule text that
each Claude hook injects at fire time. No embeddings, no regex, no truncation —
``get_text("UserPromptSubmit")`` returns every enabled rule for that hook,
concatenated in ``position`` order. Editing a rule is a single DB write.

A rule is identified by ``(hook_type, name)``: a hook type can hold several
named rules (e.g. UserPromptSubmit = "kernel" + "code-scan-policy"), each
independently enabled/ordered, and the served text is their concatenation.
"""
from __future__ import annotations

import threading
import time
from typing import Any

from app import sqldb

_LOCK = threading.Lock()

# Recognised Claude Code hook events (documentation/validation aid; free-form
# hook_type values are still accepted so new hook events need no code change).
KNOWN_HOOK_TYPES = (
    "SessionStart", "UserPromptSubmit", "PreToolUse", "PostToolUse",
    "Stop", "SubagentStop", "Notification", "PreCompact",
)


def _conn():
    return sqldb.connect()


def init() -> None:
    """Create the table if absent. Safe to call on every startup."""
    with _LOCK, _conn() as c:
        sqldb.create_table(
            c, "hook_rules",
            """
            CREATE TABLE IF NOT EXISTS hook_rules (
                id          INTEGER PRIMARY KEY AUTOINCREMENT,
                hook_type   TEXT    NOT NULL,
                name        TEXT    NOT NULL DEFAULT 'default',
                content     TEXT    NOT NULL,
                enabled     INTEGER NOT NULL DEFAULT 1,
                position    INTEGER NOT NULL DEFAULT 0,
                updated_at  TEXT    NOT NULL,
                UNIQUE(hook_type, name)
            )
            """,
            """
            CREATE COLUMN TABLE hook_rules (
                id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                hook_type   NVARCHAR(128) NOT NULL,
                name        NVARCHAR(256) NOT NULL DEFAULT 'default',
                content     NCLOB         NOT NULL,
                enabled     INTEGER       NOT NULL DEFAULT 1,
                position    INTEGER       NOT NULL DEFAULT 0,
                updated_at  NVARCHAR(32)  NOT NULL,
                UNIQUE(hook_type, name)
            )
            """,
        )
        sqldb.create_index(c, "ix_hook_rules_type", "hook_rules", "hook_type, enabled")


def set_rule(hook_type: str, content: str, name: str = "default",
             enabled: bool = True, position: int = 0) -> dict[str, Any]:
    """Insert or replace a rule, keyed by (hook_type, name)."""
    ts = time.strftime("%Y-%m-%d %H:%M:%S")
    with _LOCK, _conn() as c:
        sqldb.upsert(c, "hook_rules", ("hook_type", "name"), {
            "hook_type": hook_type, "name": name, "content": content,
            "enabled": 1 if enabled else 0, "position": position, "updated_at": ts,
        })
        row = c.execute(
            "SELECT * FROM hook_rules WHERE hook_type=? AND name=?",
            (hook_type, name),
        ).fetchone()
    return dict(row)


def get_rules(hook_type: str, enabled_only: bool = True) -> list[dict[str, Any]]:
    q = "SELECT * FROM hook_rules WHERE hook_type=?"
    args: list[Any] = [hook_type]
    if enabled_only:
        q += " AND enabled=1"
    q += " ORDER BY position ASC, id ASC"
    with _conn() as c:
        return [dict(r) for r in c.execute(q, args).fetchall()]


def get_text(hook_type: str) -> str:
    """Full plain text a hook should inject: enabled rules joined in order."""
    return "\n\n".join(r["content"] for r in get_rules(hook_type, enabled_only=True))


def list_rules(hook_type: str | None = None) -> list[dict[str, Any]]:
    with _conn() as c:
        if hook_type:
            rows = c.execute(
                "SELECT * FROM hook_rules WHERE hook_type=? ORDER BY position, id",
                (hook_type,),
            ).fetchall()
        else:
            rows = c.execute(
                "SELECT * FROM hook_rules ORDER BY hook_type, position, id"
            ).fetchall()
    return [dict(r) for r in rows]


def delete_rule(rule_id: int | None = None, hook_type: str | None = None,
                name: str | None = None) -> int:
    with _LOCK, _conn() as c:
        if rule_id is not None:
            cur = c.execute("DELETE FROM hook_rules WHERE id=?", (rule_id,))
        elif hook_type and name:
            cur = c.execute(
                "DELETE FROM hook_rules WHERE hook_type=? AND name=?",
                (hook_type, name),
            )
        else:
            raise ValueError("provide id, or hook_type+name")
        return cur.rowcount
