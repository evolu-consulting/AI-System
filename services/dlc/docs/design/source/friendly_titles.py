def apply(nodes, group):
    """Replace title/sub in place (dicts) for the given diagram group; ids without an entry are left as they are."""
    table = FRIENDLY[group]
    for n in nodes:
        if n["id"] in table:
            n["title"], n["sub"] = table[n["id"]]
    return nodes
